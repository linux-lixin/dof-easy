#!/usr/bin/env python3
"""Generate additive legacy maintenance templates from the pinned dof seed.

This does not import any dump. Only five allowlisted CREATE TABLE statements
are retained, schema-qualified, and made IF NOT EXISTS. Existing table layout
and rows are never changed. SQL execution is a separate deployment operation.
"""
import argparse
import hashlib
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parents[3]
ARCHIVE_SHA256 = '3a3d16c7981d91002835f0ba9bc89e9657b9147c5d2bc1ce347871266130609a'
TABLES = {
    'taiwan_cain_auction_cera': ('auction_history_201603', 'auction_history_buyer_201603'),
    'taiwan_cain_auction_gold': ('auction_history_201603', 'auction_history_buyer_201603'),
    'taiwan_cain_log': ('log_response_time_201604',),
}


def generate(archive, expected_sha256=ARCHIVE_SHA256):
    archive = Path(archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest() != expected_sha256:
        raise ValueError('legacy seed archive hash mismatch')
    statements = []
    with tarfile.open(archive, 'r:gz') as stream:
        members = stream.getmembers()
        for database, tables in TABLES.items():
            selected = [m for m in members if m.name == database + '.sql']
            if len(selected) != 1 or not selected[0].isfile() or selected[0].size > 2 * 1024 * 1024:
                raise ValueError('missing/duplicate/invalid SQL member: ' + database)
            with stream.extractfile(selected[0]) as content:
                sql = content.read().decode('utf-8-sig').replace('\r', '')
            for table in tables:
                pattern = r'^CREATE TABLE `' + re.escape(table) + r'`\s*\([^;]+?\)\s*ENGINE\s*=[^;]+;'
                matches = re.findall(pattern, sql, re.MULTILINE)
                if len(matches) != 1:
                    raise ValueError('missing/duplicate CREATE TABLE definition: ' + database + '.' + table)
                statement = matches[0].replace('CREATE TABLE `' + table + '`',
                    'CREATE TABLE IF NOT EXISTS `' + database + '`.`' + table + '`', 1)
                if re.search(r'\b(DROP|ALTER|TRUNCATE|INSERT|UPDATE|DELETE|REPLACE|GRANT|REVOKE)\b', statement, re.I):
                    raise ValueError('unexpected statement in allowlisted definition')
                statements.append(statement)
    return ('-- Generated by generate_compat.py from dof init_sql.tgz.\n'
            '-- Source SHA256: ' + expected_sha256 + '\n'
            '-- Additive only: existing tables and rows are preserved.\n'
            '-- Provides the historical template names used by dof monthly maintenance.\n\n'
            + '\n\n'.join(statements) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, default=ROOT / 'services/game/assets/home/template/init/init_sql.tgz')
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('compat-tables.sql'))
    args = parser.parse_args()
    sql = generate(args.archive)
    args.output.write_bytes(sql.encode('utf-8'))
    print('Generated 5 additive table definitions:', args.output)
